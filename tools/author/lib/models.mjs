// models: live CF model schema + 2–3 sample CFs per DSR model → markdown.
import { getModels, listFragments, getFragment, idField, flagField } from './aem.mjs';

const SAMPLES = {
  DM_movie: ['/content/dam/common/ja/movies', '/content/dam/common/en/movies'],
  DM_movie_related: ['/content/dam/dsr/ja/movies/standard', '/content/dam/dsr/ja/movies/tech', '/content/dam/dsr/en/movies/standard'],
  DM_product: ['/content/dam/common/ja/products'],
  DM_product_related: ['/content/dam/dsr/ja/products'],
  DM_catalog: ['/content/dam/common/ja/catalogs'],
  DM_catalog_related: ['/content/dam/dsr/ja/catalogs'],
};
const CONTENT_OF = { DM_movie_related: 'DM_movie', DM_product_related: 'DM_product', DM_catalog_related: 'DM_catalog' };

export async function modelsReport() {
  const models = await getModels();
  const out = [];
  const summary = [];
  for (const [name, folders] of Object.entries(SAMPLES)) {
    const m = models[name];
    if (!m) { out.push(`## ${name}\nNot found on DEV.\n`); continue; }
    const samples = [];
    for (const f of folders) {
      if (samples.length >= 3) break;
      for (const it of await listFragments(f, 10)) {
        if (samples.length >= 3) break;
        if (it.model?.name === name) samples.push(await getFragment(it.path));
      }
    }
    const idf = idField(m);
    const flag = flagField(m);
    const ref = CONTENT_OF[name] ? m.fields.find((f) => f.type === 'content-fragment' && f.required)?.name : null;
    summary.push(`| ${name} | ${CONTENT_OF[name] ? 'DSR CF' : 'content CF'} | ${idf ?? '– (URL = node name)'} | ${flag ?? '–'} | ${ref ? `${ref} → ${CONTENT_OF[name]}` : '–'} | ${samples.length} |`);
    out.push(`## ${name}`);
    out.push(`Model path \`${m.path}\` · ID field: **${idf ?? '– (none; URL = node name)'}** · 表示フラグ: **${flag ?? '–'}** · reference to content CF: **${ref ?? '–'}**`);
    out.push(`Samples read: ${samples.map((s) => `\`${s.path}\``).join(', ') || 'none'}\n`);
    out.push('| Field | Type (model) | Required | Multiple | Label | Samples with value | In sample data |');
    out.push('|---|---|---|---|---|---|---|');
    for (const f of m.fields) {
      const filled = samples.filter((s) => (s.fields[f.name] ?? []).some((v) => v !== '' && v !== null)).length;
      const present = samples.filter((s) => f.name in s.fields).length;
      out.push(`| ${f.name} | ${f.type}${f.type === 'enumeration' && f.values ? ` (${f.values.map((v) => v.value).join('/')})` : ''} | ${f.required ? 'yes' : ''} | ${f.multiple ? 'yes' : ''} | ${f.label} | ${filled}/${samples.length} | ${present}/${samples.length} |`);
    }
    out.push('');
  }
  const others = Object.keys(models).filter((n) => !(n in SAMPLES));
  const head = [
    '# CF models on DEV Author (read-only, generated by `node tools/author/author.mjs models`)',
    '',
    `Generated: ${new Date().toISOString()} · Source: CF OpenAPI \`/adobe/sites/cf/models\` (schema) + \`/adobe/sites/cf/fragments/{id}\` (samples). Types are the model's declared types, not guesses.`,
    '',
    '| Model | Kind | ID field (= node name) | 表示フラグ | Reference to content CF | Samples |',
    '|---|---|---|---|---|---|',
    ...summary,
    '',
    `Other models on DEV (not sampled): ${others.join(', ')}.`,
    'Rules: ID field and 表示フラグ are detected from the schema (required text field ending in `Id`; boolean labelled 表示フラグ). Date fields read back as `YYYY-MM-DD`; references as absolute paths.',
    '',
  ];
  return [...head, ...out].join('\n');
}

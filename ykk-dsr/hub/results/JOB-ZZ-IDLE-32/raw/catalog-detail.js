class CatalogDetail {
  constructor(block) {
    this.block = block;
    this.t = LABELS[getLang()] || LABELS.ja;
  }

  async init() {
    const overlay = readOverlayRows(this.block, OVERLAY_SCHEMA);
    this.block.textContent = '';

    if (overlay?.unavailable) {
      goToList(listUrl('catalog'), { replace: true });
      return;
    }

    let catalog = MOCK_CATALOG;
    if (overlay) {
      const { related, cfPath, ...cf } = overlay.data;
      // Not form-gated: no page to show, the file itself (option b). A PDF
      // and an e-book are both gated by requiresForm (DSR-655 Y3).
      if (!requiresForm(cf)) {
        const action = catalogAction(cf, { formSent: true });
        if (action?.href) window.location.replace(action.href);
        else goToList(listUrl('catalog'), { replace: true });
        return;
      }
      // Form already sent in this browser: the file, no form again.
      if (hasSentDownloadForm()) {
        const file = await fetchGatedFile(cfPath);
        if (file) {
          window.location.replace(file);
          return;
        }
      }
      catalog = {
        ...cf,
        categoryLabels: await categoryLabels(cf.catalogCategories, getLang()),
      };
    }

    this.block.append(
      el('h1', { class: 'catalog-detail-heading', textContent: this.t.heading }),
      this.#renderSummary(catalog),
      el('div', { class: 'catalog-detail-form-slot' }, CatalogDetail.#renderForm()),
    );
  }

  #renderSummary(catalog) {
    const thumb = rawAssetUrl(catalog.thumbnail) || catalog.thumbnail?._publishUrl;
    return el(
      'div',
      { class: 'catalog-detail-summary' },
      el(
        'div',
        { class: 'catalog-detail-cover' },
        el('div', { class: 'catalog-detail-cover-frame' }, el('img', { src: thumb, alt: catalog.catalogTitle, loading: 'eager' })),
        // ponytail: not wired to My List yet; add with the API (see cards.js toggleItem).
        el(
          'button',
          { type: 'button', class: 'catalog-detail-bookmark', 'aria-label': this.t.addToList },
          el(
            'picture',
            {},
            el('source', { media: SP_MEDIA, srcset: BOOKMARK_SP_URL }),
            el('img', { src: BOOKMARK_URL, alt: '' }),
          ),
        ),
      ),
      el(
        'div',
        { class: 'catalog-detail-info' },
        el('h2', { class: 'catalog-detail-title', textContent: catalog.catalogTitle }),
        el('p', { class: 'catalog-detail-description', textContent: catalog.description?.plaintext }),
        el('p', { class: 'catalog-detail-date', textContent: CatalogDetail.formatDate(catalog.publishDate) }),
        el(
          'ul',
          { class: 'catalog-detail-categories' },
          (catalog.categoryLabels || []).map((label) => el('li', { textContent: label })),
        ),
      ),
    );
  }

  /** "2022-01-20" → "2022.01.20" */
  static formatDate(value) {
    return String(value || '').slice(0, 10).replaceAll('-', '.');
  }

  static #badge(required) {
    return el('span', {
      class: `catalog-detail-badge${required ? '' : ' is-optional'}`,
      textContent: required ? '必須' : '任意',
    });
  }

  static #renderField(field) {
    const id = `catalog-detail-${field.name}`;
    const label = (tag, props) => el(
      tag,
      { class: 'catalog-detail-label', ...props },
      CatalogDetail.#badge(field.required),
      el('span', { textContent: field.label }),
    );

    if (field.type === 'checkboxes') {
      return el(
        'fieldset',
        { class: 'catalog-detail-field is-checkboxes' },
        label('legend'),
        el(
          'div',
          { class: 'catalog-detail-control' },
          field.options.map((option) => el(
            'label',
            { class: 'catalog-detail-check' },
            el('input', { type: 'checkbox', name: field.name, value: option }),
            el('span', { textContent: option }),
          )),
        ),
      );
    }

    const control = field.type === 'select'
      ? el(
        'select',
        { id, name: field.name, required: field.required },
        field.options.map((option) => el('option', { value: option, textContent: option })),
      )
      : el('input', {
        id,
        type: field.type,
        name: field.name,
        required: field.required,
        placeholder: field.placeholder,
      });

    return el(
      'div',
      { class: `catalog-detail-field is-${field.type === 'select' ? 'select' : 'text'}` },
      label('label', { htmlFor: id }),
      el('div', { class: 'catalog-detail-control' }, control),
    );
  }

  static #renderForm() {
    const check = (name, text) => el(
      'label',
      { class: 'catalog-detail-check is-consent' },
      el('input', { type: 'checkbox', name, required: true }),
      el('span', { textContent: text }),
    );

    return el(
      'form',
      { class: 'catalog-detail-form', onSubmit: (e) => e.preventDefault() },
      el('div', { class: 'catalog-detail-fields' }, FORM_FIELDS.map((field) => CatalogDetail.#renderField(field))),
      el(
        'fieldset',
        { class: 'catalog-detail-consent' },
        el('legend', { class: 'catalog-detail-label' }, CatalogDetail.#badge(true), el('span', { textContent: CONSENT.label })),
        el(
          'div',
          { class: 'catalog-detail-consent-body' },
          el('p', { textContent: CONSENT.intro }),
          check('consent_contact', CONSENT.contact),
          el('p', { textContent: CONSENT.storeNote }),
        ),
        el(
          'div',
          { class: 'catalog-detail-consent-body' },
          check('consent_store', CONSENT.store),
          el(
            'p',
            {},
            CONSENT.policyBefore,
            el('a', {
              href: CONSENT.policyHref, target: '_blank', rel: 'noopener', textContent: CONSENT.policyLink,
            }),
            CONSENT.policyAfter,
          ),
        ),
      ),
      el('button', { type: 'submit', class: 'catalog-detail-submit', textContent: CONSENT.submit }),
    );
  }
}

export default function decorate(block) {
  new CatalogDetail(block).init();
}

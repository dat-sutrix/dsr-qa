/* The form-gated catalog's file (PDF or e-book), once the visitor has sent
   the form: the page does not carry it, so it comes from the same persisted
   query the page was built from (public, like every catalog file today —
   DSR-655 Y4), and goes through the same rule as every catalog link. */
async function fetchGatedFile(cfPath) {
  const base = aemBase();
  if (!base || !cfPath) return '';
  try {
    const resp = await fetch(`${base}/graphql/execute.json/ykk/dsr-catalog-page;path=${cfPath}`);
    if (!resp.ok) return '';
    const json = await resp.json();
    const catalog = json?.data?.related?.items?.[0]?.catalog;
    return (catalog && catalogAction(catalog, { formSent: true })?.href) || '';
  } catch {
    return '';
  }
}

/* catalogCategories tag IDs → titles from the tag export, in the page
   language; the ID's last segment when a tag is missing. One request per tag
   root (`namespace:first-level`). */
async function categoryLabels(ids, lang) {
  const values = (ids || []).map((id) => String(id).trim()).filter((id) => id && !id.endsWith(':'));
  const roots = [...new Set(values.map((id) => id.split('/')[0]))];
  const maps = await Promise.all(roots.map((root) => loadTagInfo({ root, depth: 3, lang })));
  return values.map((id) => maps.map((m) => m.get(id)?.title).find(Boolean) || tagLabel(id));
}

